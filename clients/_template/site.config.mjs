function placeholders(dims) {
  return dims.map(([width, height, category], i) => {
    const n = String(i + 1).padStart(2, '0');
    return { path: `/img/placeholder/ph-${n}.svg`, width, height, category, featured: i === 0, placeholder: true, alt: `Placeholder image ${i + 1}` };
  });
}
