// Prints netlify.toml for this site from site.config.mjs (the Image CDN
// allow-list needs the Supabase project ref + bucket). Engine-owned: the
// scaffold and sync scripts regenerate it.

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { config } from '../netlify/functions/lib/config.mjs';
import { ROUTES } from '../netlify/functions/lib/site.mjs';

// Every route beyond "/" reaches page.mjs (no custom path) through a rewrite.
function pageRewrites() {
  return ROUTES.filter((r) => r !== '/')
    .map((r) => `# ${r} → page.mjs (a function with a custom path is not reachable at its default URL; see netlify/functions/page.mjs)
[[redirects]]
  from = "${r}"
  to = "/.netlify/functions/page"
  status = 200
`)
    .join('\n');
}

// Once the site lives on its own domain, the old <siteName>.netlify.app
// address answers with a 301 to the same path on the domain. Netlify does
// not do this by itself; forced host rules run before the functions
// (verified on longhornwinetours, 2026-09-22). Needs netlify.siteName.
export function hostRedirects(cfg = config) {
  const prod = new URL(cfg.productionUrl);
  const name = cfg.netlify.siteName;
  if (!name || prod.host.endsWith('.netlify.app')) return '';
  return ['https', 'http']
    .map((scheme) => `[[redirects]]
  from = "${scheme}://${name}.netlify.app/*"
  to = "${prod.origin}/:splat"
  status = 301
  force = true
`)
    .join('\n');
}

export function netlifyToml() {
  const ref = config.supabase.projectRef;
  return `# ${config.name} — owner-editable site. Deployed as its OWN Netlify site
# (project \`${config.slug}\`), decoupled from the handprotocol repo's git auto-deploy.
# Generated by scripts/gen-netlify-toml.mjs from site.config.mjs.
#
#   cd clients/${config.slug} && netlify deploy --prod --build --site <site-id>
#
# This local toml pins the publish dir and functions dir so a deploy from
# inside the monorepo never inherits the root netlify.toml (the HAND site).
[build]
  publish = "${config.netlify.publish}"
  command = ""

[functions]
  directory = "netlify/functions"
  node_bundler = "esbuild"

# Owner uploads live in Supabase Storage; Netlify Image CDN resizes them.
[images]
  remote_images = ["https://${ref.replace(/\./g, '\\\\.')}\\\\.supabase\\\\.co/storage/v1/object/public/${config.bucket}/.*"]

${hostRedirects() ? `# The old Netlify address sends everyone to the domain (one address per page).\n${hostRedirects()}\n` : ''}${pageRewrites()}
[[headers]]
  for = "/assets/*"
  [headers.values]
    Cache-Control = "public, max-age=3600, must-revalidate"

[[headers]]
  for = "/img/*"
  [headers.values]
    Cache-Control = "public, max-age=31536000, immutable"

[[headers]]
  for = "/admin/*"
  [headers.values]
    X-Robots-Tag = "noindex, nofollow"
    Cache-Control = "no-store"
    X-Frame-Options = "DENY"

[[headers]]
  for = "/*"
  [headers.values]
    X-Content-Type-Options = "nosniff"
    Referrer-Policy = "strict-origin-when-cross-origin"
    Permissions-Policy = "camera=(), microphone=(), geolocation=()"
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const out = (process.argv.find((a) => a.startsWith('--out=')) || '').slice(6) || 'netlify.toml';
  if (!config.netlify.managed && out === 'netlify.toml') {
    console.log('netlify.toml is pack-owned (site.config.mjs netlify.managed = false); not written. Print it with --out=/dev/stdout');
  } else {
    writeFileSync(out, netlifyToml());
    console.log(`wrote ${out}`);
  }
}
