const catalogs: Record<Lang, Record<MessageKey, string>> = { en, es }

const LANG_KEY = 'yuhm:lang'

export function detectLang(): Lang {
  try {
    const saved = localStorage.getItem(LANG_KEY)
    if (saved === 'en' || saved === 'es') return saved
  } catch { /* storage unavailable */ }
  const preferences = [navigator.language, ...(navigator.languages ?? [])]
  return preferences.some((tag) => tag?.toLowerCase().startsWith('es')) ? 'es' : 'en'
}

type I18nValue = {
  lang: Lang
  setLang: (lang: Lang) => void
  t: (key: MessageKey, vars?: Record<string, string | number>) => string
}

const I18nContext = createContext<I18nValue | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(detectLang)

  useEffect(() => { document.documentElement.lang = lang }, [lang])

  const setLang = useCallback((next: Lang) => {
    setLangState(next)
    try { localStorage.setItem(LANG_KEY, next) } catch { /* storage unavailable */ }
  }, [])

  const value = useMemo<I18nValue>(() => ({
    lang,
    setLang,
    t: (key, vars) => {
      let message = catalogs[lang][key] ?? en[key]
      if (vars) for (const [name, replacement] of Object.entries(vars)) message = message.split(`{${name}}`).join(String(replacement))
      return message
    },
  }), [lang, setLang])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext)
  if (!value) throw new Error('useI18n requires an I18nProvider')
  return value
}

/** Globe toggle that flips between English and Spanish and persists the choice. */
export function LanguageToggle({ className = '' }: { className?: string }) {
  const { lang, setLang } = useI18n()
  const next: Lang = lang === 'en' ? 'es' : 'en'
  return <button
    className={`language-toggle ${className}`}
    type="button"
    lang={next}
    onClick={() => setLang(next)}
    aria-label={next === 'es' ? 'Cambiar a español' : 'Switch to English'}
  ><Globe size={15} aria-hidden="true" /><span>{next === 'es' ? 'ES' : 'EN'}</span></button>
}
