const catalogs: Record<Lang, Record<RunKey, string>> = { en, es }

export type RunVars = Record<string, string | number>

/** Looks up run-sheet copy in a language, outside React. */
export function runText(lang: Lang, key: RunKey, vars?: RunVars): string {
  let message: string = catalogs[lang]?.[key] ?? en[key]
  if (vars) for (const [name, value] of Object.entries(vars)) message = message.split(`{${name}}`).join(String(value))
  return message
}

export const hasRunKey = (key: string): key is RunKey => key in en

export type RunT = (key: RunKey, vars?: RunVars) => string

export function useRunText(): { t: RunT; lang: Lang } {
  const { lang } = useI18n()
  const t = useCallback<RunT>((key, vars) => runText(lang, key, vars), [lang])
  return { t, lang }
}

/** "2 boxes", "1 loaf", "0.5 lb": a quantity with its unit in the right number. */
export function quantityText(lang: Lang, quantity: number, unit: string): string {
  const key = `unit.${unit}.${quantity === 1 ? 'one' : 'many'}`
  const shown = Number.isInteger(quantity) ? String(quantity) : quantity.toFixed(1)
  return `${shown} ${hasRunKey(key) ? runText(lang, key) : unit}`
}

/** A catalog tag in words, or the runner's own wording when it is a custom one. */
export function tagText(lang: Lang, group: 'allergy' | 'avoid' | 'want' | 'kitchen' | 'item' | 'contains' | 'tough', tag: string): string {
  const key = `${group}.${tag}`
  return hasRunKey(key) ? runText(lang, key) : tag.replace(/_/g, ' ')
}

/** People in a household, in words. */
export function peopleText(lang: Lang, count: number): string {
  return count === 1 ? runText(lang, 'common.person') : runText(lang, 'common.people', { count })
}

export function familiesText(lang: Lang, count: number): string {
  return count === 1 ? runText(lang, 'common.family') : runText(lang, 'common.families', { count })
}
